def draw(rng=None):
    """학습 30문장과 효과 확인 10문장을 겹치지 않게 새로 뽑는다."""
    import random
    rng = rng or random.Random()
    pool = POOL_CAL + POOL_EVAL
    picked = rng.sample(pool, len(CALIBRATION) + len(EVALUATION))
    return picked[:len(CALIBRATION)], picked[len(CALIBRATION):]


_SWAPS = [("회의", "외의"), ("학교", "하교"), ("경기", "겅기")]


def _garble(text):
    for right, wrong in _SWAPS:
        text = text.replace(right, wrong)
    return text


